/**
 * Builds standard Google Fonts embed URL for one or more fonts
 */
export function buildGoogleFontEmbedUrl(fontNames: string | string[]): string {
  const list = Array.isArray(fontNames) ? fontNames : [fontNames];
  const googleFonts = list.filter((name) => {
    const item = GOOGLE_FONTS_CATALOG.find(
      (f) => f.name.toLowerCase() === name.trim().toLowerCase()
    );
    return item ? item.isGoogleFont : true; // default to true if user typed a custom Google Font
  });

  if (googleFonts.length === 0) return '';

  const params = googleFonts
    .map((name) => {
      const family = name.trim().replace(/\s+/g, '+');
      return `family=${family}:wght@300;400;500;600;700;800;900`;
    })
    .join('&');

  return `https://fonts.googleapis.com/css2?${params}&display=swap`;
}

/**
 * Dynamically injects a Google Font stylesheet link tag into the document head
 */
export function loadGoogleFontDynamically(fontName: string): void {
  if (typeof document === 'undefined' || !fontName) return;
  const cleanName = fontName.trim();
  const item = GOOGLE_FONTS_CATALOG.find(
    (f) => f.name.toLowerCase() === cleanName.toLowerCase()
  );
  if (item && !item.isGoogleFont) return; // local system font, no webfont download needed

  const url = buildGoogleFontEmbedUrl(cleanName);
  if (!url) return;

  const existing = document.querySelector(`link[data-font="${cleanName}"]`);
  if (existing) return;

  const link = document.createElement('link');
  link.rel = 'stylesheet';
  link.href = url;
  link.setAttribute('data-font', cleanName);
  document.head.appendChild(link);
}

